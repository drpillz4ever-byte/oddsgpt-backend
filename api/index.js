function localGames(count, dateStr, sportFilter, seedExtra){
  let seed=0; for(let c of (dateStr||'')) seed+=c.charCodeAt(0); seed+=(seedExtra||0);
  let out=[];
  let leagues=LOCAL_LEAGUES.filter(function(l){
    if(sportFilter==='Football') return l!=='NBA' && l!=='Euroleague';
    if(sportFilter==='NBA') return l==='NBA';
    if(sportFilter==='Basketball') return l==='NBA' || l==='Euroleague';
    return true;
  });
  for(let i=0;i<count*4 && out.length<count;i++){
    let league=leagues[(seed+i*7)%leagues.length];
    let teams=LEAGUE_TEAMS[league]||[];
    if(teams.length<2) continue;
    let home=teams[(seed+i*3)%teams.length];
    let away=teams[(seed+i*5+1)%teams.length];
    if(home===away) away=teams[(i+2)%teams.length];
    let isBB=(league==='NBA'||league==='Euroleague');
    let market;
    if(isBB){ market=["Moneyline Home","Moneyline Away","Total 220.5 Over","Total 220.5 Under","Handicap -5.5","Handicap +5.5"][ (seed+i*2)%6 ]; }
    else{ market=["1X2 - Home Win","1X2 - Away Win","Double Chance 1X","Double Chance X2","Over 2.5","Over 1.5","Under 2.5","BTTS Yes","BTTS No","GG + Over 2.5"][ (seed+i*2)%10 ]; }
    let odds=(1.50+((seed+i*13)%140)/100).toFixed(2); if(parseFloat(odds)>4.5) odds=(1.80+(i%10)/10).toFixed(2);
    let conf=72+((seed+i*11)%26);
    out.push({home,away,league,market,odds,date:dateStr,confidence:conf+'%',sport:isBB?'Basketball':'Football'});
  }
  return out;
}
